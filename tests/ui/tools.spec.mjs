test('friends polling pauses when leaving tools',async({page})=>{
 await page.clock.install()
 await prepare(page);await openTools(page);await tab(page,'好友')
 await expect(page.locator('.friend-row')).toHaveCount(2)
 await page.locator('.side-nav').getByRole('button',{name:'当前角色',exact:true}).click()
 const count=await page.evaluate(()=>window.__toolCalls.filter(c=>c.cmd==='load_friends').length)
 await page.clock.fastForward(16000)
 expect(await page.evaluate(()=>window.__toolCalls.filter(c=>c.cmd==='load_friends').length)).toBe(count)
 await openTools(page)
 await page.clock.fastForward(6000)
 await expect.poll(()=>page.evaluate(()=>window.__toolCalls.filter(c=>c.cmd==='load_friends').length)).toBeGreaterThan(count)
})


test('friends hydration stops queued work while hidden and resumes on return',async({page})=>{
 await prepare(page,'&manyFriends=1')
 await page.evaluate(()=>window.__appFixture.setMode('loading'))
 await openTools(page);await tab(page,'好友')
 await expect(page.locator('.friend-row')).toHaveCount(6)
 const calls=()=>page.evaluate(()=>window.__appFixture.calls.filter(c=>c.cmd==='search_player').length)
 await expect.poll(calls).toBe(2)
 await page.locator('.side-nav').getByRole('button',{name:'当前角色',exact:true}).click()
 await page.evaluate(()=>{window.__appFixture.setMode('loaded');window.__appFixture.resolve()})
 // Let resolved IPC promises and queued workers drain; no subsequent request may start.
 await page.waitForTimeout(200)
 expect(await calls()).toBe(2)
 await openTools(page)
 await expect.poll(calls).toBeGreaterThan(2)
 await expect(page.getByTitle('刷新好友和战绩')).toBeEnabled()
 await expect(page.locator('.friend-row')).toHaveCount(6)
})
