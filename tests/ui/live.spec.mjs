import { test, expect } from '@playwright/test'
test.beforeEach(async({page})=>{
 page.__runtimeErrors=[]
 page.on('pageerror',error=>page.__runtimeErrors.push(error.message))
})
test.afterEach(async({page})=>{expect(page.__runtimeErrors).toEqual([])})
const nav=(page,name)=>page.locator('.side-nav button').filter({hasText:name}).click()
const set=(page,state)=>page.evaluate(value=>window.__liveFixture.set(value),state)
const shot=(page,info,name)=>page.screenshot({path:info.outputPath(name+'.png'),fullPage:true})
async function noPageOverflow(page){expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)}
for(const [width,height] of [[1363,836],[1040,680]]){
 test(`live states and champ-select transitions ${width}`,async({page},info)=>{
  await page.setViewportSize({width,height});await page.goto('/tests/ui/?normal=1')
  await nav(page,'实时战绩')
  await expect(page.locator('.live-empty')).toContainText('当前阶段没有可读取的真实玩家')
  await shot(page,info,'live-empty')
  await set(page,{phase:'ChampSelect',mode:'loading'})
  await expect(page.locator('.live-empty')).toContainText('正在读取双方近 50 局')
  await shot(page,info,'live-loading')
  // Leave while pending, then resolve the stale request: it must not restore a roster.
  await nav(page,'当前角色')
  await page.evaluate(()=>window.__liveFixture.resolvePending())
  expect(await page.evaluate(()=>window.__liveFixture.calls.some(c=>c.cmd==='cancel_stats_load'))).toBe(true)
  await set(page,{mode:'error'})
  await nav(page,'实时战绩')
  await expect(page.locator('.live-empty.error')).toContainText('模拟实时战绩读取失败')
  await shot(page,info,'live-error')
  await set(page,{mode:'loaded'})
  await page.locator('.live-page').getByRole('button',{name:'刷新',exact:true}).click()
  await expect(page.locator('.roster-player')).toHaveCount(10)
  await expect(page.locator('.choice-card')).toHaveCount(1)
  await expect(page.locator('.choice-state')).toContainText('海克斯选人中')
  await noPageOverflow(page);await shot(page,info,'champ-select-loaded')
  await set(page,{choiceError:true})
  await expect(page.locator('.choice-warning[role="alert"]')).toContainText('模拟板凳席读取失败',{timeout:8000})
  await set(page,{choiceError:false})
  await page.getByRole('button',{name:'重试席位读取'}).click()
  await expect(page.locator('.choice-warning[role="alert"]')).toHaveCount(0)
  await set(page,{phase:'InProgress'})
  await expect(page.locator('.choice-entry')).toBeVisible({timeout:8000})
  await expect(page.locator('.game-meta')).toContainText('游戏中')
  await shot(page,info,'live-in-game')
  await page.locator('.player-details > summary').click()
  await expect(page.locator('.player-card')).toHaveCount(10)
  await expect(page.locator('.player-error').filter({hasText:'模拟该玩家战绩暂不可用'})).toBeVisible()
  await noPageOverflow(page);await shot(page,info,'live-expanded')
  await page.locator('.player-details > summary').click()
  await page.locator('.roster-identity button').first().click()
  await expect(page.locator('.drill-tabs button')).toHaveCount(1)
  await page.getByRole('button',{name:'后退',exact:true}).click()
  await expect(page.locator('.live-page')).toBeVisible()
  await page.locator('.compact-launch').click()
  expect(await page.evaluate(()=>window.__liveFixture.calls.some(c=>c.cmd==='plugin:window|show'))).toBe(true)
  await set(page,{phase:'None',mode:'empty'})
  await expect(page.locator('.roster-player')).toHaveCount(0,{timeout:8000})
  await expect(page.locator('.live-empty')).toContainText('当前没有可读取的对局')
  await set(page,{phase:'ChampSelect',mode:'loaded'})
  await expect(page.locator('.roster-player')).toHaveCount(10,{timeout:8000})
  await expect(page.locator('.choice-card')).toHaveCount(1)
 })
}
for(const width of [360,460]){
 test(`compact real component ${width}`,async({page},info)=>{
  await page.setViewportSize({width,height:700});await page.goto('/tests/ui/?compact=1')
  await expect(page.locator('.compact-empty')).toBeVisible()
  await shot(page,info,'compact-waiting')
  await page.evaluate(()=>window.__liveFixture.emitCompact('loaded',2))
  await expect(page.locator('.compact-player')).toHaveCount(10)
  await noPageOverflow(page);await shot(page,info,'compact-loaded')
  await page.evaluate(()=>window.__liveFixture.emitCompact('empty',1))
  await expect(page.locator('.compact-player')).toHaveCount(10) // reject stale revision
  const pin=page.getByRole('button',{name:'取消置顶',exact:true})
  await pin.click();await expect(page.getByRole('button',{name:'置顶窗口',exact:true})).toHaveAttribute('aria-pressed','false')
  await set(page,{pinError:true})
  await page.getByRole('button',{name:'置顶窗口',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('置顶切换失败')
  await shot(page,info,'compact-error')
  await page.getByRole('button',{name:'回到主窗口',exact:true}).click()
  await page.getByRole('button',{name:'隐藏小窗',exact:true}).click()
  expect(await page.evaluate(()=>window.__liveFixture.calls.some(c=>c.cmd==='plugin:window|hide'))).toBe(true)
  await page.evaluate(()=>window.__liveFixture.emitCompact('empty',3))
  await expect(page.locator('.compact-empty')).toBeVisible()
  expect(await page.evaluate(()=>window.__liveFixture.calls.some(c=>c.cmd==='load_live_game'))).toBe(false)
 })
}

test('live disconnected recovery and unsupported champ-select queue',async({page},info)=>{
 await page.goto('/tests/ui/?normal=1')
 await set(page,{disconnected:true})
 await nav(page,'实时战绩')
 await expect(page.locator('.live-empty.error')).toContainText('模拟客户端未连接')
 expect(await page.evaluate(()=>window.__liveFixture.calls.filter(c=>c.cmd==='load_live_game').length)).toBe(0)
 await shot(page,info,'live-disconnected')
 await set(page,{disconnected:false,phase:'ChampSelect',queueId:450})
 await expect(page.locator('.roster-player')).toHaveCount(10,{timeout:8000})
 await expect(page.locator('.choice-state')).toContainText('当前模式尚未支持')
 await expect(page.locator('.choice-card')).toHaveCount(0)
 expect(await page.evaluate(()=>window.__liveFixture.calls.filter(c=>c.cmd==='load_champion_choices').length)).toBe(0)
 await shot(page,info,'champ-select-unsupported')
 await set(page,{queueId:2400})
 await page.locator('.live-page').getByRole('button',{name:'强制刷新',exact:true}).click()
 await expect(page.locator('.choice-state')).toContainText('海克斯选人中')
 await expect(page.locator('.choice-card')).toHaveCount(1)
 await noPageOverflow(page)
})
